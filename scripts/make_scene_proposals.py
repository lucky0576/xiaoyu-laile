import os
from docx import Document
from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

FONT = '微软雅黑'
NAVY = RGBColor(0x0D, 0x2B, 0x4E)
BLUE = RGBColor(0x12, 0x55, 0x8F)
TEAL = RGBColor(0x0F, 0x7B, 0x8A)
GREY = RGBColor(0x60, 0x70, 0x89)
BODY = RGBColor(0x3D, 0x4D, 0x66)


def set_font(run, size=10.5, bold=False, color=None):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    for a in ('w:eastAsia', 'w:ascii', 'w:hAnsi'):
        rFonts.set(qn(a), FONT)


def para(doc, text='', size=10.5, bold=False, color=None, align=None,
         before=0, after=6, line=1.6, first=0):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = line
    if first:
        pf.first_line_indent = Cm(first)
    if text:
        r = p.add_run(text)
        set_font(r, size=size, bold=bold, color=color)
    return p


def h1(doc, t):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(15)
    p.paragraph_format.space_after = Pt(7)
    p.paragraph_format.line_spacing = 1.3
    set_font(p.add_run(t), size=14.5, bold=True, color=NAVY)


def h2(doc, t):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.line_spacing = 1.3
    set_font(p.add_run(t), size=11.5, bold=True, color=BLUE)


def body(doc, t):
    return para(doc, t, size=10.5, color=BODY, first=0.74, after=6, line=1.72)


def bullet(doc, t):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.left_indent = Cm(1.05)
    pf.first_line_indent = Cm(-0.42)
    pf.space_before = Pt(0)
    pf.space_after = Pt(3)
    pf.line_spacing = 1.65
    set_font(p.add_run('· '), size=10.5, bold=True, color=TEAL)
    set_font(p.add_run(t), size=10.5, color=BODY)


def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hexcolor)
    tcPr.append(shd)


def table(doc, headers, rows, widths=None, fs=9.5):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.style = 'Table Grid'
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ''
        p = c.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(3)
        p.paragraph_format.space_after = Pt(3)
        set_font(p.add_run(h), size=fs, bold=True, color=RGBColor(0xFF, 0xFF, 0xFF))
        shade(c, '0D2B4E')
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ''
            p = cells[i].paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT if i == 0 else WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.space_before = Pt(3)
            p.paragraph_format.space_after = Pt(3)
            p.paragraph_format.line_spacing = 1.3
            set_font(p.add_run(str(v)), size=fs, color=RGBColor(0x16, 0x20, 0x2E))
            if ri % 2 == 1:
                shade(cells[i], 'F4F7FC')
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    for row in t.rows:
        row._tr.get_or_add_trPr().append(OxmlElement('w:cantSplit'))
    return t


def callout(doc, lines, fill='F0F9FA'):
    t = doc.add_table(rows=1, cols=1)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    c = t.rows[0].cells[0]
    shade(c, fill)
    c.text = ''
    first = True
    for text, bold in lines:
        p = c.paragraphs[0] if first else c.add_paragraph()
        first = False
        p.paragraph_format.space_before = Pt(3)
        p.paragraph_format.space_after = Pt(3)
        p.paragraph_format.line_spacing = 1.65
        set_font(p.add_run(text), size=10.5, bold=bold, color=NAVY if bold else BODY)
    t.rows[0]._tr.get_or_add_trPr().append(OxmlElement('w:cantSplit'))
    return t


def hrule(doc):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(8)
    pPr = p._p.get_or_add_pPr()
    pbdr = OxmlElement('w:pBdr')
    b = OxmlElement('w:bottom')
    b.set(qn('w:val'), 'single')
    b.set(qn('w:sz'), '8')
    b.set(qn('w:space'), '1')
    b.set(qn('w:color'), 'DCE3EF')
    pbdr.append(b)
    pPr.append(pbdr)


