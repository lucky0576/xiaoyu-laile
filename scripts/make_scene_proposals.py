def build(spec, out_dir):
    doc = Document()
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
    sec.left_margin = sec.right_margin = Cm(2.3)
    sec.top_margin = sec.bottom_margin = Cm(2.3)

    st = doc.styles['Normal']
    st.font.name = FONT
    st.font.size = Pt(10.5)
    st.element.rPr.rFonts.set(qn('w:eastAsia'), FONT)

    chars = []

    def T(s):
        chars.append(s)
        return s

    # 封面
    for _ in range(4):
        para(doc, '', after=0)
    para(doc, spec['title'], size=24, bold=True, color=NAVY, align=WD_ALIGN_PARAGRAPH.CENTER, after=8)
    para(doc, spec['subtitle'], size=24, bold=True, color=NAVY, align=WD_ALIGN_PARAGRAPH.CENTER, after=24)
    para(doc, spec['tagline'], size=12, color=TEAL, align=WD_ALIGN_PARAGRAPH.CENTER, after=44)
    hrule(doc)
    para(doc, '小鱼来了 · 杭州硕鱼科技有限公司', size=13, bold=True, color=NAVY,
         align=WD_ALIGN_PARAGRAPH.CENTER, after=6)
    para(doc, spec['target'], size=10.5, color=GREY, align=WD_ALIGN_PARAGRAPH.CENTER, after=34)
    hrule(doc)
    para(doc, '2026 年 11 月', size=10.5, color=GREY, align=WD_ALIGN_PARAGRAPH.CENTER, after=4)
    para(doc, '本方案仅供需求方评审使用', size=9, color=GREY, align=WD_ALIGN_PARAGRAPH.CENTER)

    doc.add_page_break()

    # 核心能力（填写用）
    h1(doc, '核心能力（填写用）')
    para(doc, '以下为可直接拷贝填入申报表单的 200 字版本。', size=9.5, color=GREY, after=8)
    callout(doc, [(spec['core'], False)])
    para(doc, f'字符数：{len(spec["core"])}（含标点）', size=9, color=GREY, before=4, after=16)

    # 产品解决方案
    h1(doc, '产品解决方案')
    for kind, content in spec['sections']:
        if kind == 'h1':
            h1(doc, content)
        elif kind == 'h2':
            h2(doc, content)
        elif kind == 'p':
            body(doc, T(content))
        elif kind == 'b':
            bullet(doc, T(content))
        elif kind == 'table':
            headers, rows, widths = content
            table(doc, headers, rows, widths)
            para(doc, '', after=6)
        elif kind == 'callout':
            lines, fill = content
            callout(doc, [(T(x), bold) for x, bold in lines], fill or 'F0F9FA')
            para(doc, '', after=6)

    # 结尾
    para(doc, '', after=10)
    hrule(doc)
    para(doc, '小鱼来了 · 杭州硕鱼科技有限公司', size=10, bold=True, color=NAVY,
         align=WD_ALIGN_PARAGRAPH.CENTER, after=3)
    para(doc, '联系人：卢云    电话：134 5669 3544', size=9.5, color=GREY,
         align=WD_ALIGN_PARAGRAPH.CENTER, after=3)
    para(doc, '邮箱：service@xiaoyulaile.online    官网：xiaoyulaile.online', size=9.5,
         color=GREY, align=WD_ALIGN_PARAGRAPH.CENTER)

    out = os.path.join(out_dir, spec['file'] + '.docx')
    doc.save(out)
    return out, sum(len(x) for x in chars)


