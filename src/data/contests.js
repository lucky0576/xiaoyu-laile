/** 距报名截止还有几天（正数=还剩，0=今天截止，负数=已截止，null=无明确截止日） */
export function daysLeft(deadline, now = Date.now()) {
  if (!deadline) return null;
  const end = Date.parse(`${deadline}T23:59:59+08:00`);
  if (!Number.isFinite(end)) return null;
  const diff = end - now;
  return Math.ceil(diff / 86400000);
}

/** 所有赛事的带倒计时视图 */
export function listWithCountdown(now = Date.now()) {
  return CONTESTS.map((c) => ({
    ...c,
    daysLeft: daysLeft(c.deadline, now),
  }));
}

